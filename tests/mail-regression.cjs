"use strict";
const assert = require("node:assert/strict");
const { createMailer, reminderStage, dateKey } = require("../functions/mail-engine");
const now = new Date("2026-09-12T15:00:00Z");
assert.equal(dateKey(now), "2026-09-12");
for (const [hours, stage] of [[73,null],[72,"3d"],[65,"3d"],[48,"2d"],[20,"2d"],[3,"3h"],[0.5,"3h"],[0,null],[-1,null]]) {
  assert.equal(reminderStage(new Date(+now + hours*3600000), now), stage);
}
assert.equal(reminderStage("bad-date", now), null);
const records = new Map();
function ref(path) { return { path, get: async () => ({ exists: records.has(path), data: () => records.get(path) }), set: async (data) => records.set(path, {...records.get(path), ...data}) }; }
const db = { collection: name => ({ doc: id => ref(`${name}/${id}`) }), runTransaction: async fn => fn({ get: r => r.get(), create: (r,d) => { assert.equal(records.has(r.path),false); records.set(r.path,d); } }) };
let deliveries = 0;
const transport = { sendMail: async m => { assert.equal(m.from.address,"sender@example.com"); assert.deepEqual(m.to,{address:"recipient@example.com"}); deliveries++; return { accepted: ["recipient@example.com"], messageId: "test" }; } };
const options = { db, transport, sender: "sender@example.com", timestamp: () => now, now: () => now };
const message = { id: "one", to: "recipient@example.com", subject: "Test", text: "Test" };
(async () => {
  const mailer = createMailer(options);
  await mailer.send(message); await mailer.send(message);
  assert.equal(deliveries,1);
  assert.equal(records.get("emailLogs/one").status,"sent");
  records.set("emailLogs/legacy", { sentAt: now });
  await mailer.send({...message,id:"legacy-new",legacyIds:["legacy"]});
  assert.equal(deliveries,1);
  await createMailer({...options,dryRun:true}).send({...message,id:"preview"});
  assert.equal(records.has("emailLogs/preview"),false);
  const failed=createMailer({...options,transport:{sendMail:async()=>{throw new Error("timeout");}}});
  await failed.send({...message,id:"uncertain"}); await failed.send({...message,id:"uncertain"});
  assert.equal(failed.report.failed,1);
  assert.equal(records.get("emailLogs/uncertain").status,"needs_review");
  await mailer.send({...message,id:"injection",to:"one@example.com,two@example.com"});
  assert.equal(deliveries,1);
  console.log("Email regression: stages, catch-up, historical logs, dry-run, uncertain delivery and recipient validation passed.");
  const data=new Map();
  const reference=path=>({path,id:path.split('/').pop(),parent:{parent:path.split('/').length>2?reference(path.split('/').slice(0,-2).join('/')):null},collection:name=>collection(`${path}/${name}`),get:async()=>({exists:data.has(path),data:()=>data.get(path)}),set:async d=>data.set(path,d)});
  const snapshot=items=>({docs:items.map(([path,d])=>({id:path.split('/').pop(),ref:reference(path),data:()=>d})),size:items.length});
  const collection=path=>({doc:id=>reference(`${path}/${id}`),get:async()=>snapshot([...data].filter(([p])=>p.startsWith(path+'/')&&p.split('/').length===path.split('/').length+1)),where:()=>({limit:()=>({get:async()=>snapshot([])})})});
  const runDb={doc:reference,collection,collectionGroup:name=>({get:async()=>snapshot([...data].filter(([p])=>p.split('/').at(-2)===name))}),runTransaction:async fn=>fn({get:r=>r.get(),create:(r,d)=>data.set(r.path,d)})};
  data.set('clinics/c/settings/clinic',{clinicName:'Clinic',clinicEmail:'clinic@example.com'});
  data.set('clinics/c/patients/p',{name:'Patient',email:'p@example.com',language:'Español',emailNotificationsEnabled:true,birthdayEmailEnabled:true,birthDate:'2000-09-12'});
  data.set('clinics/c/patients/no',{email:'no@example.com',emailNotificationsEnabled:false,birthdayEmailEnabled:true,birthDate:'2000-09-12'});
  data.set('clinics/c/appointments/a',{patientId:'p',date:new Date(+now+2*3600000).toISOString(),status:'scheduled',reminderEnabled:true});
  data.set('clinics/c/appointments/cancelled',{patientId:'p',date:new Date(+now+2*3600000).toISOString(),status:'cancelled',reminderEnabled:true});
  data.set('platformClinics/c',{name:'Clinic',status:'pilot',pilotEndsAt:'2026-09-15',language:'es'});
  data.set('platformClinics/archived',{status:'archived',pilotEndsAt:'2026-09-15'});
  data.set('platformClinics/undated',{status:'pilot'});
  data.set('platformClinics/unverified',{status:'pilot',pilotEndsAt:'2026-09-15'});
  const messages=[];
  const runOptions={db:runDb,auth:{getUser:async id=>({email:'owner@example.com',emailVerified:id!=='unverified'})},sender:'sender@example.com',transport:{verify:async()=>{},sendMail:async m=>{messages.push(m);return {accepted:['ok']};}},now:()=>now,timestamp:()=>now};
  const result=await createMailer(runOptions).run();
  assert.equal(result.sent,3);
  assert.ok(messages.some(m=>m.subject.includes('cumpleaños')));
  assert.ok(messages.some(m=>m.text.includes('no se realizará ningún cobro')));
  assert.equal(messages.filter(m=>m.to.address==='no@example.com').length,0);
  await createMailer(runOptions).run();
  assert.equal(messages.length,3);
  data.get('clinics/c/appointments/a').date=new Date(+now+3600000).toISOString();
  await createMailer(runOptions).run();
  assert.equal(messages.length,4,'rescheduling gets a new reminder key');
  console.log('Email integration: opt-ins, cancellations, verified pilot recipients, Spanish, repeated runs and rescheduling passed.');
})().catch(e=>{console.error(e);process.exitCode=1;});
