const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const source = fs.readFileSync('app.js', 'utf8');
const start = source.indexOf('function accountingReceipts(');
const end = source.indexOf('\nfunction renderAdvancedAccounting', start);
assert.ok(start >= 0 && end > start);
const state = { visits: [], payments: [], adjustments: [] };
const context = vm.createContext({ state, paymentType: (visit) => visit.paymentType || 'cash' });
vm.runInContext(source.slice(start, end), context);
state.visits = [{ id: 'legacy', date: '2026-09-01', paid: 50 }];
assert.equal(context.accountingReceipts(), 50, 'Legacy payments must be included');
state.visits = [{ id: 'mixed', date: '2026-09-01', patientPaid: 100, insurancePaid: 0 }];
state.payments = [{ visitId: 'mixed', date: '2026-09-02', method: 'card', amount: 60 }];
assert.equal(context.accountingReceipts(), 100);
assert.equal(context.accountingReceipts('', '', 'cash'), 40, 'Later card payment must not be counted again as initial cash');
assert.equal(context.accountingReceipts('', '', 'card'), 60);
assert.equal(context.accountingReceipts('2026-09-01', '2026-09-01'), 40);
assert.equal(context.accountingReceipts('2026-09-02', '2026-09-02'), 60);
state.adjustments = [{ visitId: 'mixed', type: 'refund', date: '2026-09-02', amount: 20 }];
assert.equal(context.accountingReceipts(), 80);
console.log('Accounting regression checks passed: legacy totals, mixed payment methods, date ranges, and refunds.');
